import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { transform } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const appDirectory = path.resolve(scriptDirectory, "..");
const bundlePath = path.join(appDirectory, "src", "schema", "kubernetes-v1.36.4.json");
const outputPath = path.join(appDirectory, "src", "schema", "kubernetes-v1.36.4-validators.js");
const checkOnly = process.argv.includes("--check");

const schemaBundle = JSON.parse(await readFile(bundlePath, "utf8"));
const schemaId = `https://signalforge.local/schemas/kubernetes/${schemaBundle.kubernetesVersion}`;
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  validateFormats: false,
  code: { source: true, esm: true }
});

ajv.addSchema({ $id: schemaId, definitions: schemaBundle.definitions }, schemaId);

const validatorIds = {};
const resourceExports = {};
for (const [resourceKey, definitionName] of Object.entries(schemaBundle.supportedResources)) {
  const exportName = `validate_${resourceKey.replace(/[^A-Za-z0-9_$]/g, "_")}`;
  const validatorId = `${schemaId}/resources/${encodeURIComponent(resourceKey)}`;
  ajv.addSchema({ $id: validatorId, $ref: `${schemaId}#/definitions/${definitionName}` }, validatorId);
  ajv.getSchema(validatorId);
  validatorIds[exportName] = validatorId;
  resourceExports[resourceKey] = exportName;
}

const generatedCode = standaloneCode(ajv, validatorIds);
const resourceMap = Object.entries(resourceExports)
  .map(([resourceKey, exportName]) => `  ${JSON.stringify(resourceKey)}: ${exportName}`)
  .join(",\n");
const moduleSource = [
  generatedCode.trimEnd(),
  "",
  "export const KUBERNETES_VALIDATORS = Object.freeze({",
  resourceMap,
  "});",
  ""
].join("\n");
const transformed = await transform(moduleSource, {
  format: "esm",
  legalComments: "none",
  minify: true,
  target: "es2022"
});
const output = `// Generated by scripts/build-kubernetes-validators.mjs. Do not edit manually.\n${transformed.code}`;

if (checkOnly) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  const normalizeLineEndings = (value) => value.replace(/\r\n?/g, "\n");
  if (normalizeLineEndings(existing) !== normalizeLineEndings(output)) {
    throw new Error("Precompiled Kubernetes validators are missing or stale; run npm run validators:build.");
  }
  console.log(`Verified ${path.relative(appDirectory, outputPath)} for ${Object.keys(resourceExports).length} resources.`);
} else {
  await writeFile(outputPath, output);
  console.log(`Wrote ${path.relative(appDirectory, outputPath)} with ${Object.keys(resourceExports).length} precompiled validators.`);
}
